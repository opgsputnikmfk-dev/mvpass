"""Render the Russian report from actual stored results, never estimated values."""
import json
from pathlib import Path

root = Path(__file__).parent / 'round2'
d = json.loads((root / 'results.json').read_text())
labels = {'channel_4h': 'Пробой диапазона, 4 часа',
          'ema_4h': 'Пересечение средних, 4 часа',
          'compression_1h': 'Выход из сжатия, 1 час'}

def name(x):
    return f'{labels[x["strategy"]]} · {x["parameter"]}'

def pf(x):
    return 'нет убыточных сделок' if x['profit_factor'] is None else f'{x["profit_factor"]:.2f}'

def row(x, label):
    return (f'| {label} | {x["trades"]} | {x["return_pct"]:+.2f}% | '
            f'{x["win_rate_pct"]:.1f}% | {pf(x)} | {x["max_drawdown_pct"]:.2f}% |')

lines = ['# AI Crypto — вторая серия исследований', '',
         '**Решение: ' + ('кандидат прошёл исторические критерии; требуется дальнейшее наблюдение.'
                          if d['accepted'] else 'кандидат не прошёл критерии допуска. Прибыльная замена боту не подтверждена.') + '**', '',
         'Это воспроизводимый исторический эксперимент, а не результат реальной торговли. '
         'Работающий бот не изменён. Все проценты ниже относятся к учебному счёту 10 000 USDT без плеча.', '',
         '## Что проверили', '',
         '- BTCUSDT, ETHUSDT и SOLUSDT: минутные цены Binance USD-M Futures, опубликованные ставки финансирования и минутные mark prices.',
         '- Шесть заранее заданных вариантов: пробой 20/55 четырёхчасовых свечей; пересечение EMA 12/48 или 24/96; часовой пробой 20/40 свечей после сжатия.',
         '- Начальный стоп — 3 ATR; затем он подтягивается за закрытыми свечами. Фиксированной цели нет; максимальное удержание — семь дней.',
         '- Решение только после закрытия свечи; вход через одну полную минуту после границы. Изменённый стоп действует со следующей минуты.',
         '- Комиссия 0,055% с каждой стороны плюс неблагоприятное исполнение 0,045% с каждой стороны. Финансирование учтено отдельно по истории. В стресс-сценарии исполнение ухудшено до 0,09% с каждой стороны, комиссия прежняя.',
         '- Плановый риск до 0,25% счёта на сделку; ограничения общего риска, суммы позиций и одинакового направления. Начало новых сделок останавливается при дневном снижении 2% или общей просадке 8%; это не гарантия предельного убытка.', '',
         '## Разделение истории', '',
         'Разработка: январь–июнь 2025. Выбор: июль–сентябрь 2025. '
         'После фиксации кандидата — две отдельные проверки: октябрь–ноябрь 2025 и 1–23 октября 2026. '
         'Каждая проверка начинает с 10 000 USDT без открытых позиций. '
         'Период 24–30 октября 2026 исключён: он уже проверялся для предыдущего бота. '
         'Январь–сентябрь 2026 также не используется как новая проверка. '
         'В датах JSON правая граница не включается. Декабрь 2024 используется для прогрева индикаторов.', '',
         '## Все варианты до финальной проверки', '',
         '| Вариант | Разработка: результат | Выбор: результат | Сделки при выборе | Прибыль / убытки |',
         '|---|---:|---:|---:|---:|']
for a, b in zip(d['development'], d['selection']):
    lines.append(f'| {name(b)} | {a["return_pct"]:+.2f}% | {b["return_pct"]:+.2f}% | {b["trades"]} | {pf(b)} |')
lines += ['', f'Зафиксированный кандидат: **{name(d["chosen"])}**. '
          f'Прошёл предварительный отбор: **{"да" if d["chosen"]["selection_qualified"] else "нет; выбран только для диагностики"}**.', '',
          '## Результаты после фиксации', '',
          '| Проверка | Сделки | Изменение счёта | Прибыльных сделок | Прибыль / убытки | Макс. просадка |',
          '|---|---:|---:|---:|---:|---:|']
for i, (a, b) in enumerate(zip(d['holdout'], d['stress'])):
    label = 'Октябрь–ноябрь 2025' if i == 0 else '1–23 октября 2026'
    lines += [row(a, label), row(b, label + ', повышенные расходы')]
lines += ['', '«Прибыль / убытки» — сумма чистых выигрышей, делённая на абсолютную сумму чистых проигрышей. '
          'Значение меньше 1 означает убыток. Просадка учитывает открытые позиции и рассчитана по минутам; '
          'на графике показаны только дневные точки.', '',
          '## Устойчивость параметров и допуск', '']
for x in d['sensitivity']:
    lines.append(f'- Соседний параметр {x["parameter"]}: {x["return_pct"]:+.2f}% на периоде выбора, {x["trades"]} сделок.')
checks = [
    ('Предварительный отбор: положительный результат и не менее 20 сделок', d['chosen']['selection_qualified']),
    ('Не менее 50 сделок суммарно в двух финальных периодах', sum(x['trades'] for x in d['holdout']) >= 50),
    ('Оба соседних параметра положительны', all(x['net_usdt'] > 0 for x in d['sensitivity'])),
    ('Оба финальных периода положительны, прибыль/убытки ≥1,15 и просадка <8%', all(x['net_usdt'] > 0 and (x['profit_factor'] is None or x['profit_factor'] >= 1.15) and x['max_drawdown_pct'] < 8 for x in d['holdout'])),
    ('Оба периода остаются положительными при повышенных расходах', all(x['net_usdt'] > 0 for x in d['stress']))]
lines += ['', *[f'- {label}: **{"да" if ok else "нет"}**.' for label, ok in checks], '',
          '## Графики', '', '![Исторические проверки и сделки на графике BTC](charts.png)', '',
          'Отметки входов и выходов на ценовом графике показывают время событий по ценам минутных свечей; '
          'они не изображают точные цены исполнения с проскальзыванием. Полный журнал событий включён в results.json.', '',
          '## Ограничения', '',
          'Проверены три выбранных крупных актива, а не вся биржа. Повторный поиск среди стратегий повышает риск случайно найти красивую историю. '
          'Два периода проверки не доказывают устойчивость во всех режимах рынка, особенно короткое окно октября 2026. '
          'Проверка соседних параметров выполнена на периоде выбора; новые параметры не выбирались по финальным результатам. '
          'Настоящие исторические bid/ask, очередь исполнения и точная цена расчёта финансирования неизвестны: '
          'использованы фиксированные расходы и открытие минутной mark-свечи. '
          'Внутриминутный порядок событий приблизителен; при неоднозначности применяется стоп первым. '
          'Конечный результат не является обещанием доходности и не подтверждает 80% прибыльных сделок.', '',
          'Исследования AQR [Time Series Momentum](https://www.aqr.com/insights/research/journal-article/time-series-momentum) '
          'и [Which Trend Is Your Friend?](https://www.aqr.com/insights/research/journal-article/which-trend-is-your-friend) '
          'послужили мотивацией проверить трендовые правила. Их результаты на других активах и горизонтах не доказывают прибыльность этих криптостратегий.', '',
          '## Воспроизведение', '',
          'Из корня репозитория, с установленными numpy, pandas и matplotlib:', '', '```bash',
          'python -m unittest discover -s research -p "test_*.py"',
          'python research/search_round2.py --cache /tmp/ai_crypto_futures --output research/round2',
          'python research/plot_round2.py', 'python research/report_round2.py', '```', '',
          'SHA256 исходных архивов записаны в manifest.json; загрузчик сравнивает их с опубликованными CHECKSUM. '
          'Пропущенный день mark prices за 29 июня 2026 дополнен официальными дневными архивами. '
          'Проверки движка охватывают расходы, финансирование, баланс, порядок стопов, отсутствие использования будущих свечей и структуру периодов.', '']
(root / 'RESULTS_RU.md').write_text('\n'.join(lines))
print('Wrote', root / 'RESULTS_RU.md')
